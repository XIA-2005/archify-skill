test('fixture baseline passes the canonical renderer with straight shared outputs', {timeout: 30000}, t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'archify-incremental-fixture-test-'));
  t.after(() => fs.rmSync(dir, {recursive: true, force: true, maxRetries: 3, retryDelay: 100}));
  const baseline = getIncrementalFixtures()[0].baseline;
  fs.writeFileSync(path.join(dir, 'candidate.json'), JSON.stringify(baseline));
  const renderer = fileURLToPath(new URL('../renderers/architecture/render-architecture.mjs', import.meta.url));
  const result = spawnSync(process.execPath, [renderer, path.join(dir, 'candidate.json'), path.join(dir, 'diagram.html'), '--layout-json'],
    {cwd: dir, encoding: 'utf8', timeout: 25000, windowsHide: true});
  assert.ifError(result.error);
  assert.equal(result.status, 0, result.stdout + result.stderr);
  const layout = JSON.parse(result.stdout);
  assert.equal(layout.ok, true);
  assert.equal(layout.components.length, 6);
  assert.equal(layout.connections.length, 5);
  assert.ok(layout.connections.filter(edge => edge.from === 'shared').every(edge => edge.points.length === 2 && edge.points[0][0] === edge.points[1][0]));
  assert.ok(layout.viewBox[0] <= 1200 && layout.viewBox[1] <= 800);
});

test('controlled update oracle is repeatable, self-contained and separate from real project changes', () => {
  const fixtures = getIncrementalFixtures();
  assert.deepEqual(fixtures, getIncrementalFixtures());
  assert.equal(new Set(fixtures.map(item => item.id)).size, fixtures.length);
  assert.ok(['text-condition', 'add-branch', 'shared-consumer'].every(id => fixtures.some(item => item.id === id)));
  for (const fixture of fixtures) {
    validateSchema('architecture', fixture.baseline);
    validateSchema('architecture', fixture.expectedSemantic);
    assert.equal(fixture.experiment.realFirmwareChange, false);
    assert.equal(fixture.experiment.oracleFrozenBeforeModel, true);
    assert.equal(fixture.expectedFacts.semanticSha256, semanticHash(fixture.expectedSemantic));
    assert.ok(fixture.baseline.components.every(node => node.pos?.length === 2 && node.size?.length === 2));
    assert.equal(extractSemantic(fixture.expectedSemantic).removed.length, 0);
    assert.equal(fixture.geometryPolicy.fixed, undefined);
    for (const source of [fixture.sourceBefore, fixture.sourceAfter]) {
      assert.equal(source.origin, 'controlled-executable-fixture');
      for (const file of source.files) assert.equal(file.sha256, createHash('sha256').update(file.content).digest('hex'));
    }
    for (const fact of fixture.expectedFacts.components) {
      const source = fixture.sourceAfter.files.find(file => file.path === fact.sources[0].path);
      assert.ok(source, `No source for ${fact.id}`);
      const lines = source.content.trimEnd().split('\n');
      assert.ok(fact.sources[0].line >= 1 && fact.sources[0].end_line <= lines.length);
    }
  }
  fixtures[0].baseline.components[0].pos[0] = 9999;
  assert.equal(getIncrementalFixtures()[0].baseline.components[0].pos[0], 40);
});

// Execute the supplied module sources, rather than trusting a graph generated by
// the same extractor under test. The expected traces were declared beforehand.
for (const fixture of getIncrementalFixtures()) test(`source execution agrees with predeclared facts: ${fixture.id}`, async () => {
  const functions = new Map();
  for (const file of fixture.sourceAfter.files) {
    const module = await import(`data:text/javascript;base64,${Buffer.from(file.content).toString('base64')}`);
    const id = file.path.split('/').at(-1).replace('.mjs', '');
    const fact = fixture.expectedFacts.components.find(item => item.id === id);
    assert.deepEqual(module.description, {label: fact.label, sublabel: fact.sublabel, type: fact.type, owner: fact.owner});
    functions.set(id, module[id]);
  }
  for (const execution of fixture.expectedFacts.executions) {
    const trace = [], io = {trace: id => trace.push(id)};
    for (const [id, implementation] of functions) io[id] = implementation;
    io.input(structuredClone(execution.task), io);
    assert.deepEqual(trace, execution.trace, `${fixture.id}: ${JSON.stringify(execution.task)}`);
  }
});

test('authorization, audit branch and shared fanout are explicit near the affected relation', () => {
  const fixtures = getIncrementalFixtures();
  const condition = fixtures.find(item => item.id === 'text-condition');
  assert.equal(condition.expectedSemantic.connections.find(edge => edge.id === 'dispatch-worker').label, 'ready + authorized');
  assert.equal(condition.expectedSemantic.components.find(node => node.id === 'worker').label, 'Task worker');
  assert.equal(condition.expectedSemantic.components.find(node => node.id === 'worker').id, 'worker');
  const branch = fixtures.find(item => item.id === 'add-branch');
  assert.deepEqual(branch.expectedSemantic.connections.at(-1), {id: 'worker-audit', from: 'worker', to: 'audit', label: 'audit enabled'});
  const shared = fixtures.find(item => item.id === 'shared-consumer');
  assert.deepEqual(shared.expectedSemantic.connections.filter(edge => edge.from === 'shared').map(edge => edge.to), ['storeA', 'storeB', 'storeC']);
  assert.equal(shared.expectedSemantic.cards, undefined);
});

test('no-op fixture has no content proposal and destructive changes are separately auditable', () => {
  const fixtures = getIncrementalFixtures(), baselineSha256 = 'a'.repeat(64);
  const noop = fixtures.find(item => item.id === 'no-op');
  assert.equal(compareSemantics(noop.expectedSemantic, noop.baseline).equivalent, true);
  assert.deepEqual(noop.sourceBefore, noop.sourceAfter);
  assert.deepEqual(buildFixtureProposal(noop, baselineSha256), {schemaVersion: 1, baselineSha256, operations: []});
  const removed = fixtures.find(item => item.id === 'remove-consumer');
  const operations = buildFixtureProposal(removed, baselineSha256).operations;
  assert.ok(operations.some(op => op.op === 'remove' && op.target === 'component' && op.id === 'storeB'));
  assert.ok(operations.some(op => op.op === 'remove' && op.target === 'connection' && op.id === 'shared-storeB'));
  assert.ok(operations.every(op => op.evidence.length > 0));
  assert.ok(!removed.expectedSemantic.connections.some(edge => edge.from === 'storeB' || edge.to === 'storeB'));
});

test('predeclared negative oracles detect lost condition, missing call and reversed feedback', () => {
  const negatives = getIncrementalOracleNegatives();
  assert.equal(negatives.length, 3);
  for (const negative of negatives) {
    validateSchema('architecture', negative.incorrectSemantic);
    assert.equal(compareSemantics(negative.expectedSemantic, negative.incorrectSemantic).equivalent, false, negative.id);
  }
});
